export function validateCzechChapters(data=CZ_2024_CHAPTERS){
 if(!Array.isArray(data)||data.length!==48)throw Error('Expected 48 official 2024 budget chapters');
 const ids=new Set();
 let totalHundredths=0;
 for(const chapter of data){
   if(!Number.isInteger(chapter.id)||ids.has(chapter.id)||
     typeof chapter.name!=='string'||chapter.name.trim().length<4||
     !Number.isFinite(chapter.actualThousandCzk)||chapter.actualThousandCzk<0)
     throw Error('Invalid Czech 2024 chapter amount or ID');
   ids.add(chapter.id);
   const cents=Math.round(chapter.actualThousandCzk*100);
   if(Math.abs(chapter.actualThousandCzk*100-cents)>0.001)
     throw Error('Excessive monetary precision in official chapter');
   totalHundredths+=cents;
 }
 if(totalHundredths!==223679077748)throw Error('2024 chapter totals do not match Ministry of Finance Table 7');
 return data;
}
export function czechChapterData(country,year){
 return country==='CZ'&&year===2024?CZ_2024_CHAPTERS:null;
}
export function czechChaptersSorted(){
 return [...validateCzechChapters()].sort((a,b)=>b.actualThousandCzk-a.actualThousandCzk);
}
